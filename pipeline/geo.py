R_EARTH = 6371.0


def area_km2(poly):
    """Área de un polígono esférico (lon, lat en grados) con la fórmula de L'Huilier aproximada por proyección
    de igual área (Lambert cilíndrica) en la longitud de cada tramo."""
    tot = 0.0
    n = len(poly)
    for i in range(n):
        lo1, la1 = map(math.radians, poly[i])
        lo2, la2 = map(math.radians, poly[(i + 1) % n])
        dlo = lo2 - lo1
        tot += dlo * (2 + math.sin(la1) + math.sin(la2))
    return abs(tot) * R_EARTH ** 2 / 2


def laea(poly, lon0, lat0):
    """Proyección acimutal de Lambert de igual área (km) centrada en (lon0, lat0)."""
    l0, p0 = math.radians(lon0), math.radians(lat0)
    out = []
    for lo, la in poly:
        l, p = math.radians(lo), math.radians(la)
        k = math.sqrt(2 / (1 + math.sin(p0) * math.sin(p) + math.cos(p0) * math.cos(p) * math.cos(l - l0)))
        x = R_EARTH * k * math.cos(p) * math.sin(l - l0)
        y = R_EARTH * k * (math.cos(p0) * math.sin(p) - math.sin(p0) * math.cos(p) * math.cos(l - l0))
        out.append((x, y))
    return out


def centroid(poly):
    return (sum(p[0] for p in poly) / len(poly), sum(p[1] for p in poly) / len(poly))


